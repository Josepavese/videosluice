package routing

import (
	"errors"
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/Josepavese/videosluice/config"
)

const (
	ControlSchema         = "video-broker.routing-control.v2"
	ControlActionRead     = "read"
	ControlActionPreview  = "preview"
	ControlActionApply    = "apply"
	ControlActionRollback = "rollback"
	ControlActionProgress = "progress"

	ControlOperationRunning   = "running"
	ControlOperationSucceeded = "succeeded"
	ControlOperationFailed    = "failed"
	ControlOperationDegraded  = "degraded"
)

// ControlRequest is the bounded standalone IPC command. Selections remain
// opaque catalog option IDs; raw paths, codecs and hardware policy are never
// accepted through this surface.
type ControlRequest struct {
	Schema           string            `json:"schema"`
	RequestID        string            `json:"request_id"`
	Action           string            `json:"action"`
	ExpectedRevision uint64            `json:"expected_revision,omitempty"`
	Selections       map[string]string `json:"selections,omitempty"`
	SourceSelections map[string]string `json:"source_selections"`
	OperationID      string            `json:"operation_id,omitempty"`
}

type ControlResponse struct {
	Schema    string                          `json:"schema"`
	RequestID string                          `json:"request_id"`
	OK        bool                            `json:"ok"`
	Catalog   *ControlCatalog                 `json:"catalog,omitempty"`
	Plan      *Plan                           `json:"plan,omitempty"`
	Preview   *Preview                        `json:"preview,omitempty"`
	Operation *ControlOperation               `json:"operation,omitempty"`
	Error     *ControlError                   `json:"error,omitempty"`
	Runtime   map[string]ControlStreamRuntime `json:"runtime,omitempty"`
}

// ControlStreamRuntime is a public media observation bound to a confirmed
// selection and generation. It deliberately contains no device paths or
// hardware implementation details.
type ControlStreamRuntime struct {
	SourceRef    string    `json:"source_ref"`
	Generation   uint64    `json:"generation"`
	Available    bool      `json:"available"`
	State        string    `json:"state"`
	RequestedFPS int       `json:"requested_fps"`
	TargetFPS    int       `json:"target_fps"`
	ObservedFPS  float64   `json:"observed_fps"`
	WindowMS     int64     `json:"window_ms"`
	MeasuredAt   time.Time `json:"measured_at,omitempty"`
}

type ControlError struct {
	Code    string `json:"code"`
	Message string `json:"message"`
	Phase   string `json:"phase,omitempty"`
}

// ControlCatalog is the safe public projection of the central authority. It
// deliberately excludes device paths, source identities, worker providers,
// accelerator policy and endpoint paths. Embedders may attach localized labels
// to these stable opaque IDs without changing the standalone contract.
type ControlCatalog struct {
	Revision    string                           `json:"revision"`
	Sources     []string                         `json:"sources"`
	Streams     map[string]ControlStreamCatalog  `json:"streams"`
	SourceModes map[string]map[string]SourceMode `json:"source_modes"`
}

type ControlStreamCatalog struct {
	Type    string                         `json:"type"`
	Options map[string]ControlStreamOption `json:"options"`
}

type ControlStreamOption struct {
	SourceRef   string   `json:"source_ref"`
	Codec       string   `json:"codec,omitempty"`
	PixelFormat string   `json:"pixel_format,omitempty"`
	Width       int      `json:"width"`
	Height      int      `json:"height"`
	FPS         int      `json:"fps"`
	BitrateKbps int      `json:"bitrate_kbps,omitempty"`
	Content     string   `json:"content,omitempty"`
	RateControl string   `json:"rate_control,omitempty"`
	SourceModes []string `json:"source_modes"`
}

// ControlOperation is an immutable snapshot of an asynchronous apply or
// rollback. Times are UTC RFC3339Nano strings generated by the control server.
type ControlOperation struct {
	OperationID      string        `json:"operation_id"`
	Action           string        `json:"action"`
	State            string        `json:"state"`
	Phase            string        `json:"phase"`
	ExpectedRevision uint64        `json:"expected_revision"`
	StartedAt        string        `json:"started_at"`
	FinishedAt       string        `json:"finished_at,omitempty"`
	Plan             *Plan         `json:"plan,omitempty"`
	Error            *ControlError `json:"error,omitempty"`
}

func ProjectControlCatalog(catalog Catalog) (ControlCatalog, error) {
	normalized, err := NormalizeCatalog(catalog)
	if err != nil {
		return ControlCatalog{}, err
	}
	view := ControlCatalog{
		Revision:    normalized.Revision,
		Sources:     make([]string, 0, len(normalized.Sources)),
		Streams:     make(map[string]ControlStreamCatalog, len(normalized.Streams)),
		SourceModes: make(map[string]map[string]SourceMode, len(normalized.Sources)),
	}
	for sourceID := range normalized.Sources {
		view.Sources = append(view.Sources, sourceID)
		view.SourceModes[sourceID] = make(map[string]SourceMode)
		for _, modeID := range sourceModeIDs(normalized, sourceID) {
			source, _ := sourceForMode(normalized, sourceID, modeID)
			view.SourceModes[sourceID][modeID] = SourceMode{Format: source.Format, Width: source.Width, Height: source.Height, FPS: source.FPS}
		}
	}
	sort.Strings(view.Sources)
	for streamID, stream := range normalized.Streams {
		projected := ControlStreamCatalog{
			Type: stream.Type, Options: make(map[string]ControlStreamOption, len(stream.Options)),
		}
		for optionID, option := range stream.Options {
			modes := []string{}
			for _, modeID := range sourceModeIDs(normalized, option.SourceRef) {
				source, _ := sourceForMode(normalized, option.SourceRef, modeID)
				if _, err := config.NormalizeStream(streamID, option.streamConfig(stream), source); err == nil {
					modes = append(modes, modeID)
				}
			}
			projected.Options[optionID] = ControlStreamOption{
				SourceRef: option.SourceRef, Codec: option.Codec,
				PixelFormat: option.PixelFormat, Width: option.Width,
				Height: option.Height, FPS: option.FPS,
				BitrateKbps: option.BitrateKbps, Content: option.Content,
				RateControl: option.RateControl,
				SourceModes: modes,
			}
		}
		view.Streams[streamID] = projected
	}
	return view, nil
}

func ValidateControlRequest(request ControlRequest) error {
	if request.SourceSelections != nil && request.Action != ControlActionPreview && request.Action != ControlActionApply {
		return errors.New("source selections require preview or apply")
	}
	if request.Schema != ControlSchema {
		return fmt.Errorf("unsupported routing control schema=%q", request.Schema)
	}
	if !idPattern.MatchString(request.RequestID) {
		return errors.New("routing control request_id is invalid")
	}
	if request.Action != strings.ToLower(strings.TrimSpace(request.Action)) {
		return errors.New("routing control action is not canonical")
	}
	switch request.Action {
	case ControlActionRead:
		if request.ExpectedRevision != 0 || request.Selections != nil || request.OperationID != "" {
			return errors.New("routing read accepts no revision, selections or operation")
		}
	case ControlActionPreview, ControlActionApply:
		if request.ExpectedRevision == 0 || len(request.Selections) == 0 || request.OperationID != "" {
			return errors.New("routing preview/apply requires revision and selections")
		}
	case ControlActionRollback:
		if request.ExpectedRevision == 0 || request.Selections != nil || request.OperationID != "" {
			return errors.New("routing rollback requires only a revision")
		}
	case ControlActionProgress:
		if request.ExpectedRevision != 0 || request.Selections != nil || !idPattern.MatchString(request.OperationID) {
			return errors.New("routing progress requires only a valid operation_id")
		}
	default:
		return fmt.Errorf("unknown routing control action=%q", request.Action)
	}
	return nil
}
